from __future__ import annotations

import json
import re
from pathlib import Path


def safe_path(root: Path, relative: str) -> Path:
    candidate = (root / relative).resolve()
    if candidate != root and root not in candidate.parents:
        raise ValueError("Path escapes the configured APOLO workspace.")
    return candidate


def create_project(root: Path, name: str, description: str) -> dict:
    slug = re.sub(r"[^a-zA-Z0-9_-]+", "-", name.strip()).strip("-").lower()
    if not slug:
        raise ValueError("Project name must contain letters or numbers.")
    project = safe_path(root, slug)
    project.mkdir(parents=True, exist_ok=True)
    (project / "src").mkdir(exist_ok=True)
    (project / "src" / "server").mkdir(exist_ok=True)
    (project / "src" / "client").mkdir(exist_ok=True)
    (project / "src" / "shared").mkdir(exist_ok=True)
    manifest = {
        "name": name,
        "description": description,
        "tree": {
            "$className": "DataModel",
            "ReplicatedStorage": {"$className": "ReplicatedStorage", "Shared": {"$path": "src/shared"}},
            "ServerScriptService": {"$className": "ServerScriptService", "Server": {"$path": "src/server"}},
            "StarterPlayer": {
                "$className": "StarterPlayer",
                "StarterPlayerScripts": {"$className": "StarterPlayerScripts", "Client": {"$path": "src/client"}},
            },
        },
    }
    (project / "default.project.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (project / "README.md").write_text(
        f"# {name}\n\n{description}\n\nGenerated by APOLO Roblox MCP Server.\n",
        encoding="utf-8",
    )
    return {"project": slug, "path": str(project), "files": ["default.project.json", "README.md"]}


def write_text(root: Path, project: str, relative: str, content: str) -> dict:
    base = safe_path(root, project)
    if not base.is_dir():
        raise FileNotFoundError(f"Project does not exist: {project}")
    target = safe_path(base, relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return {"path": str(target.relative_to(base)), "bytes": target.stat().st_size}


def list_files(root: Path, project: str) -> list[str]:
    base = safe_path(root, project)
    if not base.is_dir():
        raise FileNotFoundError(f"Project does not exist: {project}")
    return sorted(str(p.relative_to(base)) for p in base.rglob("*") if p.is_file())
